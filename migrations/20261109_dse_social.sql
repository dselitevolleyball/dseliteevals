-- DS Elite Social (Drew, Oct 28 2026): "a social media crafting service that
-- automatically takes photos that were uploaded to the site, creates a
-- collage, or a bunch of photos post with pictures, a caption, etc. I should
-- get a quick approval once it has been built" - and "an intro to coaches
-- post that sends surveys to coaches and when they respond, crafts a poster".
--
-- Posts go to DS Elite's own Facebook Page (and its Instagram) through the
-- club's Meta app. Nothing is posted until someone approves it, in Slack or
-- in HQ -> Social. See DSE_SOCIAL_SETUP.md and api/_lib/dse-social*.js.
-- Run: node scripts/run-sql.mjs migrations/20261109_dse_social.sql   (safe to run twice)

-- ── posts ───────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.dse_social_posts (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind          text NOT NULL DEFAULT 'photos' CHECK (kind IN ('photos', 'coach_intro')),
  -- collage: one image made of several photos; carousel: several photos in
  -- one post (Facebook multi-photo, Instagram carousel); single: one photo;
  -- poster: a designed graphic (coach intros)
  format        text NOT NULL DEFAULT 'collage' CHECK (format IN ('collage', 'carousel', 'single', 'poster')),
  status        text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'approved', 'publishing', 'published', 'failed', 'skipped')),
  title         text,
  team_name     text,               -- the data's team name ("12 Rise 1"); people see "12 Rise"
  event_label   text,
  photo_ids     bigint[] NOT NULL DEFAULT '{}',   -- player_photos this post was made from
  photos        jsonb NOT NULL DEFAULT '[]',      -- the picks, in order: [{photo_id?, path, url, w, h, note}]
  caption       text,
  hashtags      text[] NOT NULL DEFAULT '{}',
  design        jsonb NOT NULL DEFAULT '{}',      -- what the graphic says (poster headline, quote, facts; collage header)
  asset_url     text,                             -- the rendered collage / poster (public bucket dse-social)
  platforms     text[] NOT NULL DEFAULT '{facebook,instagram}',
  scheduled_at  timestamptz,                      -- approved posts go out at this time (null = as soon as approved)
  published_at  timestamptz,
  external_ids  jsonb NOT NULL DEFAULT '{}',      -- {facebook, instagram}
  error         text,
  intro_id      bigint,
  ai            jsonb NOT NULL DEFAULT '{}',
  slack         jsonb NOT NULL DEFAULT '{}',      -- the approval DMs: [{channel, ts}]
  created_by    text,
  approved_by   text,
  approved_at   timestamptz,
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS dse_social_posts_status_idx ON public.dse_social_posts (status, scheduled_at);

-- ── coach intros ────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.dse_coach_intros (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  coach_roster_id  bigint REFERENCES public.coach_roster (id) ON DELETE SET NULL,
  name             text NOT NULL,
  email            text,
  phone            text,
  teams            text[] NOT NULL DEFAULT '{}',
  token            uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
  questions        jsonb NOT NULL DEFAULT '[]',   -- [{q, a}]
  photos           jsonb NOT NULL DEFAULT '[]',   -- [{path, url, caption, w, h}]
  consent          boolean NOT NULL DEFAULT false,
  status           text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'sent', 'answered', 'drafted', 'posted', 'cancelled')),
  sent_via         text[] NOT NULL DEFAULT '{}',
  sent_at          timestamptz,
  reminded_at      timestamptz,
  answered_at      timestamptz,
  post_id          bigint REFERENCES public.dse_social_posts (id) ON DELETE SET NULL,
  error            text,
  created_by       text,
  created_at       timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS dse_coach_intros_status_idx ON public.dse_coach_intros (status);

-- ── settings (one row) ──────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.dse_social_settings (
  id               int PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  auto_photos      boolean NOT NULL DEFAULT true,      -- draft photo posts from new uploads by itself
  min_photos       int NOT NULL DEFAULT 3,             -- a batch needs this many usable photos
  platforms        text[] NOT NULL DEFAULT '{facebook,instagram}',
  approvers        text[] NOT NULL DEFAULT '{drew@dselitevolleyball.com}',   -- who gets the Slack approval
  hashtags         text[] NOT NULL DEFAULT '{DSElite,DSEliteVolleyball,ClubVolleyball,DrippingSprings}',
  intro_questions  jsonb NOT NULL DEFAULT '[]',
  intro_time       text NOT NULL DEFAULT '18:30',      -- approved coach intros go out one a day at this time (Central)
  last_scan_at     timestamptz,
  updated_at       timestamptz NOT NULL DEFAULT now()
);
INSERT INTO public.dse_social_settings (id) VALUES (1) ON CONFLICT (id) DO NOTHING;

-- ── keeping photos and players off social ───────────────────────────────────
-- The upload page tells families "if you'd rather your daughter wasn't in
-- anything we post, tell us". no_social is where that's honoured: none of her
-- family's uploads are ever picked. social_hidden keeps one photo out.
ALTER TABLE public.player_photos ADD COLUMN IF NOT EXISTS social_hidden boolean NOT NULL DEFAULT false;
ALTER TABLE public.player_photos ADD COLUMN IF NOT EXISTS social_post_id bigint;
ALTER TABLE public.players ADD COLUMN IF NOT EXISTS no_social boolean NOT NULL DEFAULT false;

-- ── storage: what gets posted must be public for Facebook to fetch it ───────
-- Only the photos picked for a post (resized copies) and the rendered
-- graphics go here; the family uploads stay in the private team-photos bucket.
INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES ('dse-social', 'dse-social', true, 26214400, ARRAY['image/jpeg', 'image/png', 'image/webp'])
ON CONFLICT (id) DO UPDATE SET public = true, file_size_limit = EXCLUDED.file_size_limit, allowed_mime_types = EXCLUDED.allowed_mime_types;

-- ── access: HQ admins read; everything else goes through the service role ──
ALTER TABLE public.dse_social_posts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.dse_coach_intros ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.dse_social_settings ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS dse_social_posts_admin_read ON public.dse_social_posts;
CREATE POLICY dse_social_posts_admin_read ON public.dse_social_posts FOR SELECT USING (public.is_admin_coach());
DROP POLICY IF EXISTS dse_coach_intros_admin_read ON public.dse_coach_intros;
CREATE POLICY dse_coach_intros_admin_read ON public.dse_coach_intros FOR SELECT USING (public.is_admin_coach());
DROP POLICY IF EXISTS dse_social_settings_admin_read ON public.dse_social_settings;
CREATE POLICY dse_social_settings_admin_read ON public.dse_social_settings FOR SELECT USING (public.is_admin_coach());
