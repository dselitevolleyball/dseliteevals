-- A connected Gmail: its Google refresh token (server only - no policy lets a
-- browser read this table) and where the poll is up to.
CREATE TABLE IF NOT EXISTS public.mail_accounts (
  email          text PRIMARY KEY,
  refresh_token  text,
  enabled        boolean NOT NULL DEFAULT true,
  connected_at   timestamptz,             -- mail before this is never drafted (no backlog flood)
  connected_by   text,
  last_poll_at   timestamptz,
  last_error     text,
  updated_at     timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.mail_accounts ENABLE ROW LEVEL SECURITY;

-- One row per incoming email looked at: drafted (Slack), ignored (newsletter,
-- receipt...), sent, skipped, or answered in Gmail before a decision.
CREATE TABLE IF NOT EXISTS public.mail_drafts (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account        text NOT NULL,
  gmail_id       text NOT NULL,
  thread_id      text,
  message_id     text,                    -- the RFC Message-ID, for In-Reply-To
  references_ids text,
  from_email     text,
  from_name      text,
  reply_to       text,
  subject        text,
  received_at    timestamptz,
  body           text,                    -- their message, trimmed
  draft          text,
  status         text NOT NULL DEFAULT 'pending',   -- pending | sent | skipped | answered | ignored | failed
  reason         text,                    -- why ignored / Claude's note / the error
  slack_channel  text,
  slack_ts       text,
  sent_gmail_id  text,
  decided_by     text,
  decided_at     timestamptz,
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now(),
  UNIQUE (account, gmail_id)
);
CREATE INDEX IF NOT EXISTS mail_drafts_slack_idx ON public.mail_drafts (slack_channel, slack_ts);
CREATE INDEX IF NOT EXISTS mail_drafts_recent_idx ON public.mail_drafts (created_at DESC);
ALTER TABLE public.mail_drafts ENABLE ROW LEVEL SECURITY;
-- No policies: only the server (service role) reads or writes either table.
