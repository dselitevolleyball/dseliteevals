-- ── touches: every time someone reached out (form, email to info@, text opt-in, newsletter)
CREATE TABLE IF NOT EXISTS public.dssc_touches (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contact_id  bigint REFERENCES public.dssc_contacts (id) ON DELETE CASCADE,
  kind        text NOT NULL,          -- form | email | text_optin | newsletter
  source      text,
  detail      text,
  ref         text UNIQUE,            -- inq:<id> / msg:<id> / sms:<phone> / news:<email>, so nothing is logged twice
  at          timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS dssc_touches_contact_idx ON public.dssc_touches (contact_id, at DESC);

-- A phone as +1XXXXXXXXXX (US), or null.
CREATE OR REPLACE FUNCTION public.dssc_e164(p text) RETURNS text LANGUAGE sql IMMUTABLE AS $$
  SELECT CASE WHEN d ~ '^\d{10}$' THEN '+1' || d WHEN d ~ '^1\d{10}$' THEN '+' || d ELSE NULL END
  FROM (SELECT regexp_replace(coalesce(p, ''), '\D', '', 'g') AS d) x
$$;

-- Add or update a person from anything they sent us, and log the touch.
-- Matches by email, then by phone. Never overwrites a name or phone we
-- already have; fills gaps, adds the source and what they asked about.
CREATE OR REPLACE FUNCTION public.dssc_intake(p_email text, p_name text, p_phone text, p_source text, p_kind text, p_detail text, p_ref text, p_interest text, p_at timestamptz)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_email text := lower(trim(coalesce(p_email, '')));
  v_ok    boolean;
  v_phone text := public.dssc_e164(p_phone);
  v_name  text := regexp_replace(trim(coalesce(p_name, '')), '\s+', ' ', 'g');
  v_first text; v_last text; v_id bigint;
  v_at    timestamptz := coalesce(p_at, now());
  v_int   text := nullif(lower(trim(coalesce(p_interest, ''))), '');
BEGIN
  v_ok := v_email ~ '^[^\s@]+@[^\s@]+\.[^\s@]+$';
  IF v_name <> '' AND v_name !~ '@' THEN
    v_first := split_part(v_name, ' ', 1);
    v_last := nullif(trim(substr(v_name, length(v_first) + 1)), '');
  END IF;
  IF v_ok THEN SELECT id INTO v_id FROM dssc_contacts WHERE lower(email) = v_email LIMIT 1; END IF;
  IF v_id IS NULL AND v_phone IS NOT NULL THEN
    SELECT id INTO v_id FROM dssc_contacts WHERE right(regexp_replace(coalesce(phone, ''), '\D', '', 'g'), 10) = right(v_phone, 10)
      ORDER BY (email IS NOT NULL) DESC, updated_at DESC NULLS LAST LIMIT 1;
  END IF;
  IF v_id IS NULL THEN
    IF NOT v_ok AND v_phone IS NULL THEN RETURN NULL; END IF;
    INSERT INTO dssc_contacts (email, first_name, last_name, phone, sources, interests, last_touch_at, created_at, updated_at)
    VALUES (CASE WHEN v_ok THEN v_email END, v_first, v_last, v_phone, ARRAY[p_source], CASE WHEN v_int IS NULL THEN '{}'::text[] ELSE ARRAY[v_int] END, v_at, now(), now())
    ON CONFLICT (email) DO NOTHING RETURNING id INTO v_id;
    IF v_id IS NULL THEN SELECT id INTO v_id FROM dssc_contacts WHERE lower(email) = v_email LIMIT 1; END IF;
  ELSE
    UPDATE dssc_contacts SET
      first_name = coalesce(nullif(first_name, ''), v_first),
      last_name  = coalesce(nullif(last_name, ''), v_last),
      phone      = coalesce(phone, v_phone),
      email      = coalesce(email, CASE WHEN v_ok AND NOT EXISTS (SELECT 1 FROM dssc_contacts c2 WHERE lower(c2.email) = v_email) THEN v_email END),
      sources    = CASE WHEN p_source = ANY (coalesce(sources, '{}')) THEN sources ELSE coalesce(sources, '{}') || p_source END,
      interests  = CASE WHEN v_int IS NULL OR v_int = ANY (interests) THEN interests ELSE interests || v_int END,
      last_touch_at = greatest(coalesce(last_touch_at, v_at), v_at),
      updated_at = now()
    WHERE id = v_id;
  END IF;
  INSERT INTO dssc_touches (contact_id, kind, source, detail, ref, at)
  VALUES (v_id, p_kind, p_source, left(p_detail, 300), p_ref, v_at)
  ON CONFLICT (ref) DO NOTHING;
  RETURN v_id;
END $$;

-- What an inquiry is about, as an interest ("volleyball", "parties", "rentals"…).
CREATE OR REPLACE FUNCTION public.dssc_inquiry_interest(sport text, kind text) RETURNS text LANGUAGE sql IMMUTABLE AS $$
  SELECT CASE
    WHEN nullif(lower(sport), '') IS NOT NULL AND lower(sport) NOT IN ('other', 'any', 'n/a') THEN lower(sport)
    WHEN lower(kind) IN ('party', 'birthday') THEN 'parties'
    WHEN lower(kind) IN ('rental', 'rentals') THEN 'rentals'
    WHEN lower(kind) IN ('opengym', 'open_gym') THEN 'open_gym'
    WHEN lower(kind) IN ('membership') THEN 'membership'
    WHEN lower(kind) IN ('league') THEN 'leagues'
    WHEN lower(kind) IN ('reach') THEN 'reach'
    ELSE NULL END
$$;

-- Website forms and emails to info@ (site_inquiries, DSSC only).
CREATE OR REPLACE FUNCTION public.dssc_intake_inquiry() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF coalesce(NEW.site, 'dssc') <> 'dssc' OR coalesce(NEW.is_test, false) THEN RETURN NEW; END IF;
  IF TG_OP = 'UPDATE' THEN
    -- Marked spam: forget the touch, and the person if that's all we had.
    IF NEW.status = 'spam' AND coalesce(OLD.status, '') <> 'spam' THEN
      DELETE FROM dssc_contacts c WHERE c.id IN (SELECT contact_id FROM dssc_touches WHERE ref = 'inq:' || NEW.id)
        AND c.sources = ARRAY['inquiry'] AND NOT EXISTS (SELECT 1 FROM dssc_touches t WHERE t.contact_id = c.id AND t.ref <> 'inq:' || NEW.id)
        AND NOT EXISTS (SELECT 1 FROM dssc_participation p WHERE p.contact_id = c.id) AND NOT EXISTS (SELECT 1 FROM dssc_purchases p WHERE p.contact_id = c.id)
        AND NOT EXISTS (SELECT 1 FROM dssc_orders o WHERE o.contact_id = c.id);
      DELETE FROM dssc_touches WHERE ref = 'inq:' || NEW.id;
      RETURN NEW;
    END IF;
    IF NEW.status = 'spam' OR (NEW.email IS NOT DISTINCT FROM OLD.email AND NEW.phone IS NOT DISTINCT FROM OLD.phone) THEN RETURN NEW; END IF;
  END IF;
  IF NEW.status = 'spam' THEN RETURN NEW; END IF;
  PERFORM public.dssc_intake(NEW.email, NEW.name, NEW.phone, 'inquiry', CASE WHEN NEW.kind = 'email' THEN 'email' ELSE 'form' END,
    concat_ws(' · ', nullif(initcap(replace(coalesce(NEW.kind, ''), '_', ' ')), ''), nullif(NEW.sport, ''), nullif(NEW.topic, ''), left(regexp_replace(coalesce(NEW.message, ''), '\s+', ' ', 'g'), 160)),
    'inq:' || NEW.id, public.dssc_inquiry_interest(NEW.sport, NEW.kind), NEW.created_at);
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS dssc_intake_inquiry ON public.site_inquiries;
CREATE TRIGGER dssc_intake_inquiry AFTER INSERT OR UPDATE OF email, phone, status ON public.site_inquiries FOR EACH ROW EXECUTE FUNCTION public.dssc_intake_inquiry();

-- A family emailing info@ again on an existing thread is a touch too.
CREATE OR REPLACE FUNCTION public.dssc_intake_inbox_message() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE q record;
BEGIN
  IF NEW.direction IS DISTINCT FROM 'inbound' THEN RETURN NEW; END IF;
  SELECT site, status, is_test, email, name, phone INTO q FROM site_inquiries WHERE id = NEW.inquiry_id;
  IF q IS NULL OR coalesce(q.site, 'dssc') <> 'dssc' OR coalesce(q.is_test, false) OR q.status = 'spam' THEN RETURN NEW; END IF;
  PERFORM public.dssc_intake(coalesce(NEW.from_email, q.email), coalesce(NEW.from_name, q.name), q.phone, 'inquiry', 'email',
    concat_ws(' · ', nullif(NEW.subject, ''), left(regexp_replace(coalesce(NEW.body_text, ''), '\s+', ' ', 'g'), 160)), 'msg:' || NEW.id, NULL, NEW.created_at);
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS dssc_intake_inbox_message ON public.site_inbox_messages;
CREATE TRIGGER dssc_intake_inbox_message AFTER INSERT ON public.site_inbox_messages FOR EACH ROW EXECUTE FUNCTION public.dssc_intake_inbox_message();

-- The club texts opt-in form (/dssc-texts): a phone and a name.
CREATE OR REPLACE FUNCTION public.dssc_intake_sms_consent() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF NEW.brand IS DISTINCT FROM 'dssc' THEN RETURN NEW; END IF;
  PERFORM public.dssc_intake(NULL, NEW.name, NEW.phone, 'texts-form', 'text_optin',
    'Signed up for club texts' || CASE WHEN nullif(NEW.player_name, '') IS NOT NULL THEN ' (' || NEW.player_name || ')' ELSE '' END,
    'sms:' || right(regexp_replace(NEW.phone, '\D', '', 'g'), 10), NULL, coalesce(NEW.consented_at, now()));
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS dssc_intake_sms_consent ON public.sms_consents;
CREATE TRIGGER dssc_intake_sms_consent AFTER INSERT ON public.sms_consents FOR EACH ROW EXECUTE FUNCTION public.dssc_intake_sms_consent();

-- ── do they answer? Club texts per phone, marketing email events per address
CREATE OR REPLACE VIEW public.dssc_sms_stats WITH (security_invoker = true) AS
SELECT right(regexp_replace(t.phone, '\D', '', 'g'), 10) AS phone10,
       count(*) FILTER (WHERE m.direction = 'outbound') AS sent,
       count(*) FILTER (WHERE m.direction = 'inbound') AS replies,
       max(m.created_at) FILTER (WHERE m.direction = 'inbound') AS last_reply_at,
       max(m.created_at) FILTER (WHERE m.direction = 'outbound') AS last_sent_at
FROM public.sms_threads t JOIN public.sms_messages m ON m.thread_id = t.id
WHERE t.brand = 'dssc'
GROUP BY 1;
CREATE OR REPLACE VIEW public.dssc_email_stats WITH (security_invoker = true) AS
SELECT lower(email) AS email,
       count(*) FILTER (WHERE type ILIKE '%open%') AS opens,
       count(*) FILTER (WHERE type ILIKE '%click%') AS clicks,
       count(DISTINCT item_id) FILTER (WHERE type ILIKE '%open%' OR type ILIKE '%click%') AS emails_engaged,
       max(at) FILTER (WHERE type ILIKE '%open%') AS last_open_at,
       max(at) FILTER (WHERE type ILIKE '%click%') AS last_click_at
FROM public.mkt_email_events GROUP BY 1;

-- ── campaigns: an audience, an offer, and steps on the marketing calendar ──
CREATE TABLE IF NOT EXISTS public.crm_campaigns (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name            text NOT NULL,
  goal            text,                               -- winback | membership | privates | try_new | parties | referral | promo | custom
  status          text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'scheduled', 'live', 'done', 'cancelled')),
  segment         jsonb NOT NULL DEFAULT '{}',        -- shared/crm-segments.js filters
  audience_label  text,
  audience_count  int,
  audience_ids    bigint[] NOT NULL DEFAULT '{}',     -- who it was planned for (for results)
  offer           jsonb NOT NULL DEFAULT '{}',        -- {kind, value, code, expires, applies_to, url, line}
  channels        text[] NOT NULL DEFAULT '{email,text}',
  steps           jsonb NOT NULL DEFAULT '[]',        -- [{day, channel, who, subject, preheader, headline, body, cta_text, sms, item_id}]
  item_ids        bigint[] NOT NULL DEFAULT '{}',     -- mkt_items it put on the calendar
  starts_on       date,
  idea_key        text,
  notes           text,
  created_by      text,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now()
);
