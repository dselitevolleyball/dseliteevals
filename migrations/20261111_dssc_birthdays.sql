-- DSSC birthday emails (Drew, Oct 29 2026): "First email should be 75 days
-- before their birthday for up to kids turning 13 inviting them to have their
-- birthday party at our warehouse and offer a $50 dollar off coupon ... Second
-- email should be sent on their birthday wishing them a happy birthday and
-- giving them $35 dollars off any product at DSSC."
-- See api/_lib/dssc-birthdays.js and CRM_SETUP.md (Birthday emails).
-- Run: node scripts/run-sql.mjs migrations/20261111_dssc_birthdays.sql   (safe to run twice)

-- One row: on/off, the codes and the rules. Off until a director turns it on.
CREATE TABLE IF NOT EXISTS public.dssc_birthday_settings (
  id              int PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  party_on        boolean NOT NULL DEFAULT false,
  birthday_on     boolean NOT NULL DEFAULT false,
  party_days      int NOT NULL DEFAULT 75,       -- the party invite goes this many days before
  party_min_age   int NOT NULL DEFAULT 3,        -- turning at least ...
  party_max_age   int NOT NULL DEFAULT 13,       -- ... and at most this
  party_off       int NOT NULL DEFAULT 50,       -- dollars
  party_code      text NOT NULL DEFAULT 'BDAY50',      -- Playbook: $50 off one party package, once per customer, expires Dec 1 2027
  party_book_days int NOT NULL DEFAULT 0,        -- "book by": this many days after the email; 0 = no date
  birthday_max_age int NOT NULL DEFAULT 18,      -- birthday wishes for kids turning up to this
  birthday_off    int NOT NULL DEFAULT 35,
  birthday_code   text NOT NULL DEFAULT 'BDAY35',      -- Playbook: $35 off anything, once per customer, no expiration
  birthday_valid_days int NOT NULL DEFAULT 0,    -- the gift is good for this many days; 0 = no date
  updated_by      text,
  updated_at      timestamptz NOT NULL DEFAULT now()
);
INSERT INTO public.dssc_birthday_settings (id) VALUES (1) ON CONFLICT (id) DO NOTHING;

-- Every birthday email, one per child per kind per birthday, so nobody gets it twice.
CREATE TABLE IF NOT EXISTS public.dssc_birthday_sends (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  participant_id bigint REFERENCES public.dssc_participants (id) ON DELETE CASCADE,
  contact_id     bigint REFERENCES public.dssc_contacts (id) ON DELETE SET NULL,
  kind           text NOT NULL CHECK (kind IN ('party', 'birthday')),
  birthday       date NOT NULL,                 -- the birthday it was for (this year's)
  turns          int,
  email          text,
  status         text NOT NULL DEFAULT 'sending',   -- sending | sent | failed | skipped
  reason         text,                         -- why skipped / the error
  resend_id      text,
  slots          jsonb,                        -- the party times the email showed
  created_at     timestamptz NOT NULL DEFAULT now(),
  sent_at        timestamptz,
  UNIQUE (participant_id, kind, birthday)
);
CREATE INDEX IF NOT EXISTS dssc_birthday_sends_recent_idx ON public.dssc_birthday_sends (created_at DESC);

ALTER TABLE public.dssc_birthday_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.dssc_birthday_sends ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS dssc_birthday_settings_director_read ON public.dssc_birthday_settings;
CREATE POLICY dssc_birthday_settings_director_read ON public.dssc_birthday_settings FOR SELECT USING (public.is_dssc_director());
DROP POLICY IF EXISTS dssc_birthday_sends_director_read ON public.dssc_birthday_sends;
CREATE POLICY dssc_birthday_sends_director_read ON public.dssc_birthday_sends FOR SELECT USING (public.is_dssc_director());
